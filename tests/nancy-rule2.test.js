const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");

const PHRASE = "أنا مس نانسي";
// The only three legitimate carriers of the self-introduction: the opening
// greetings (nancy_greet_1/2/3). Every other spoken string must not contain it.
const GREETINGS = [
  "أهلاً يا ملك ماثيو! أنا مس نانسي، وبحبك أوي! يلا نلعب ونتعلم مع بعض!",
  "أنا مس نانسي وبحبك يا ماثيو! وحشتني أوي، يلا نبدأ يوم جميل مع بعض!",
  "أهلاً يا بطلي ماثيو! أنا مس نانسي، أنا فخورة بيك أوي! يلا نشوف هنلعب إيه النهارده!",
];

// Rule (2), round 3.2.2 P0-3: «أنا مس نانسي» belongs ONLY in the opening
// greeting, never in section intros (quiz, stories, tracing, colour, memory,
// touch games, praise). This is the regression gate: any reword that brings
// the phrase back anywhere fails here.
test("rule (2): exactly the 3 opening greetings contain «أنا مس نانسي» — corpus + code", () => {
  // 1) Corpus: exactly the 3 greeting keys carry the phrase.
  const corpus = JSON.parse(fs.readFileSync(path.join(root, "audio-src/corpus.json"), "utf8"));
  const corpusHits = corpus.filter(e => String(e.text).includes(PHRASE)).map(e => e.key).sort();
  assert.deepEqual(
    corpusHits,
    ["nancy_greet_1", "nancy_greet_2", "nancy_greet_3"],
    "corpus keys carrying the phrase must be exactly the 3 opening greetings, got: " + corpusHits.join(", ")
  );
  for (const e of corpus.filter(e => String(e.text).includes(PHRASE))) {
    assert.ok(GREETINGS.includes(e.text), e.key + ": greeting text drifted from the canonical wording");
  }

  // 2) Code: every phrase-carrying line must be one of the 3 greetings.
  // Scanned: *.js / *.html / *.json under the repo root, except:
  //  - tests/ (assertions and test names quote the phrase on purpose),
  //  - www/ + android/ (stale copies regenerated by the workflow),
  //  - node_modules/ + .git,
  //  - the generated voice packs (voice-clips-pack-*.js,
  //    voice-clips-text-1.js — rebuilt by the coordinator from corpus.json).
  const skipDirs = new Set(["tests", "www", "android", "node_modules", ".git", "audio-src"]);
  const skipFiles = new Set(["voice-clips-text-1.js"]);
  const hits = [];
  const walk = dir => {
    for (const name of fs.readdirSync(dir)) {
      const p = path.join(dir, name);
      const st = fs.statSync(p);
      if (st.isDirectory()) {
        if (!skipDirs.has(name)) walk(p);
      } else if (/\.(js|html|json)$/.test(name) && !skipFiles.has(name) && !/^voice-clips-pack-.*\.js$/.test(name)) {
        const text = fs.readFileSync(p, "utf8");
        text.split("\n").forEach((line, i) => {
          if (line.includes(PHRASE)) hits.push(path.relative(root, p) + ":" + (i + 1) + ": " + line.trim().slice(0, 120));
        });
      }
    }
  };
  walk(root);
  const bad = hits.filter(h => !GREETINGS.some(g => h.includes(g)));
  assert.equal(bad.length, 0, "code lines carrying the phrase outside the 3 greetings:\n" + bad.join("\n"));
  for (const g of GREETINGS) {
    assert.ok(hits.some(h => h.includes(g)), "opening greeting missing from code: " + g);
  }
});
