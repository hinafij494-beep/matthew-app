#!/usr/bin/env python3
"""Build the recorded teacher-voice clip files from audio-src/corpus.json + audio-src/opus/*.ogg.
Output is CHUNKED so each file stays push-friendly (< ~1MB):
  voice-clips-data-N.js  — window.__matthewClipData chunks (key -> base64 opus)
  voice-clips-text-N.js  — window.__matthewClipText chunks (normalized text -> key)
  voice-clips.js         — runtime: merges chunks into MatthewClips (playKey/play/playSequence).
Normalization folds Arabic-Indic digits and strips diacritics/punctuation, mirrored in the runtime."""
import json, base64, os, re, sys, glob
root = os.path.dirname(os.path.abspath(__file__))
corpus = json.load(open(os.path.join(root, "audio-src/corpus.json")))
DIGITS = {"٠":"0","١":"1","٢":"2","٣":"3","٤":"4","٥":"5","٦":"6","٧":"7","٨":"8","٩":"9"}
def norm(s):
    s = "".join(DIGITS.get(c, c) for c in s)
    s = re.sub(r"[ً-ٰٟـ]", "", s)
    s = re.sub(r"[^ء-يa-zA-Z0-9 ]", " ", s)
    return re.sub(r"\s+", " ", s).strip().lower()
SEG_MAX = 55000  # max base64 chars per entry (GitHub push arg limit); long clips split into key~N segments
by_key, by_text, exact, missing = {}, {}, {}, []
# Round 3.2.1: 71 normed texts are shared by 2+ DISTINCT exact texts (bare
# glyph vs vocalised syllable: 'ب' vs 'بَ'/'بُ'/'بِ'; long vs vocalised
# syllable: 'با' vs 'بَا'; Latin vs Arabic-Indic digit: '1' vs '١'; upper
# vs lower letter: 'A' vs 'a'; plain vs vocalised word: 'أسد' vs 'أَسَد').
# BY_TEXT (normalised) cannot tell them apart — the last corpus entry wins
# the norm, so a bare glyph resolves to a syllable clip (the note-1 bug) and
# 'با' resolves to rd_part_0_0 instead of rd_syl_1_3. The EXACT map
# (diacritic-preserving, consulted first by keyFor) MUST therefore contain
# every text whose norm collides with another distinct text, so the exact
# spoken string always wins over the normalised guess.
from collections import defaultdict as _dd
_norm_texts = _dd(set)
for _e in corpus:
    _norm_texts[norm(_e["text"])].add(_e["text"].strip())
for e in corpus:
    p = os.path.join(root, "audio-src/opus", e["key"] + ".ogg")
    if not os.path.exists(p):
        missing.append(e["key"]); continue
    b64 = base64.b64encode(open(p, "rb").read()).decode()
    if len(b64) <= SEG_MAX:
        by_key[e["key"]] = b64
    else:
        for i in range(0, len(b64), SEG_MAX):
            by_key[f"{e['key']}~{i // SEG_MAX + 1}"] = b64[i:i + SEG_MAX]
    by_text[norm(e["text"])] = e["key"]
    _t = e["text"].strip()
    _bare = re.sub(r"[ً-ٰٟـ]", "", _t).strip()
    if re.search(r"[ً-ٟ]", _t) and len(_bare) <= 3:
        exact[_t] = e["key"]
    if len(_norm_texts[norm(e["text"])]) > 1:
        exact[_t] = e["key"]
if missing:
    print("MISSING audio for", len(missing), "entries, e.g.", missing[:8]); sys.exit(1)

LIMIT = 1_900_000
def chunks(mapping, var):
    items = sorted(mapping.items())
    groups, cur, size = [], {}, 0
    for k, v in items:
        entry = json.dumps(k, ensure_ascii=False) + ":" + json.dumps(v, ensure_ascii=False)
        if size + len(entry) > LIMIT and cur:
            groups.append(cur); cur, size = {}, 0
        cur[k] = v; size += len(entry) + 1
    if cur: groups.append(cur)
    return ["window." + var + "=window." + var + "||[];window." + var + ".push(" + json.dumps(g, ensure_ascii=False) + ");\n" for g in groups]

for old in glob.glob(os.path.join(root, "voice-clips-pack-*.js")) + glob.glob(os.path.join(root, "voice-clips-text-*.js")):
    os.remove(old)
data_files, text_files = [], []
for i, js in enumerate(chunks(by_key, "__matthewClipData"), 1):
    name = f"voice-clips-pack-{i}.js"; open(os.path.join(root, name), "w").write(js); data_files.append(name)
for i, js in enumerate(chunks(by_text, "__matthewClipText"), 1):
    name = f"voice-clips-text-{i}.js"; open(os.path.join(root, name), "w").write(js); text_files.append(name)
if exact and text_files:
    with open(os.path.join(root, text_files[0]), "a") as fh:
        fh.write("window.__matthewClipExact=window.__matthewClipExact||[];window.__matthewClipExact.push(" + json.dumps(exact, ensure_ascii=False) + ");\n")

runtime = """// voice-clips.js — مقاطع صوت الميس المسجلة (صوت أنثوي طبيعي بالعامية المصرية، Opus).
// Generated by build-voice-clips.py — data lives in voice-clips-data-*.js / voice-clips-text-*.js chunks.
(() => {
  const BY_KEY = Object.assign({}, ...(window.__matthewClipData || []));
  for (const k of Object.keys(BY_KEY)) { const t = k.indexOf("~"); if (t > 0) { const base = k.slice(0, t); BY_KEY[base] = (BY_KEY[base] || "") + BY_KEY[k]; delete BY_KEY[k]; } }
  const BY_TEXT = Object.assign({}, ...(window.__matthewClipText || []));
  const EXACT = Object.assign({}, ...(window.__matthewClipExact || []));
  // Round 3.2.2 P1-5: the chunk arrays are ~56MB of base64 once merged —
  // free them after the snapshot so the audio is not cached twice.
  window.__matthewClipData = null; window.__matthewClipText = null; window.__matthewClipExact = null;
  if (Object.keys(BY_KEY).length < 2000) console.warn("[matthew-clips] only " + Object.keys(BY_KEY).length + " clips loaded (expected ~2100)");
  const DIGITS = {"٠":"0","١":"1","٢":"2","٣":"3","٤":"4","٥":"5","٦":"6","٧":"7","٨":"8","٩":"9"};
  const norm = value => String(value || "").replace(/[٠-٩]/g, c => DIGITS[c]).replace(/[ً-ٰٟـ]/g, "").replace(/[^ء-يa-zA-Z0-9 ]/g, " ").replace(/\s+/g, " ").trim().toLowerCase();
  const urls = {}; const urlOrder = []; const URL_CACHE_MAX = 30; let audio = null;
  const supported = () => { try { const a = audio || new Audio(); return !!a.canPlayType && a.canPlayType('audio/ogg; codecs="opus"') !== ""; } catch (_) { return false; } };
  const urlFor = key => { if (!urls[key]) { const bin = atob(BY_KEY[key]); const bytes = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i); urls[key] = URL.createObjectURL(new Blob([bytes], { type: "audio/ogg" })); urlOrder.push(key); while (urlOrder.length > URL_CACHE_MAX) { const old = urlOrder.shift(); if (old !== key && urls[old]) { try { URL.revokeObjectURL(urls[old]); } catch (_) {} delete urls[old]; } } } return urls[key]; };
  const playKey = key => { if (!BY_KEY[key] || !supported()) return false; try { if (!audio) audio = new Audio(); audio.onended = null; audio.pause(); audio.src = urlFor(key); audio.currentTime = 0; const p = audio.play(); if (p && p.catch) p.catch(() => {}); return true; } catch (_) { return false; } };
  // Round 3.2.2 P0-5: the EXACT map must respect caller language. A bare
  // Latin digit ("5") has an EXACT entry pointing at the ENGLISH tracing
  // clip (tr_ennum_5) — in an Arabic context that is the numbers trap, so
  // Arabic callers skip EXACT for bare digits and use BY_TEXT (the Arabic
  // digit clip, e.g. tr_num_5 / num_digit_15). English callers keep EXACT.
  const isBareDigit = text => /^[0-9٠-٩]+$/.test(String(text || "").trim());
  const keyFor = (text, lang) => {
    const t = String(text || "").trim();
    const arabic = String(lang || "").toLowerCase().startsWith("ar");
    if (arabic && isBareDigit(t)) return BY_TEXT[norm(t)];
    return EXACT[t] || BY_TEXT[norm(t)];
  };
  const play = (text, lang) => { const key = keyFor(text, lang); return key ? playKey(key) : false; };
  // Round 3.2.2 P0-4 (review 2.5): element-by-element — an item with no
  // recorded clip is skipped silently instead of dropping the whole
  // question to device TTS.
  const playSequence = (texts, lang) => { const keys = []; for (const t of texts || []) { const k = keyFor(t, lang); if (k) keys.push(k); } if (!keys.length || !supported()) return false; try { if (!audio) audio = new Audio(); let i = 0; const next = () => { if (i >= keys.length) { audio.onended = null; return; } audio.src = urlFor(keys[i++]); const pr = audio.play(); if (pr && pr.catch) pr.catch(() => {}); }; audio.onended = next; next(); return true; } catch (_) { return false; } };
  const stop = () => { try { if (audio) { audio.onended = null; audio.pause(); } } catch (_) {} };
  window.MatthewClips = { playKey, play, playSequence, stop, has: key => !!BY_KEY[key], keys: Object.keys(BY_KEY), count: Object.keys(BY_TEXT).length };
})();
"""
open(os.path.join(root, "voice-clips.js"), "w").write(runtime)
print("data chunks:", len(data_files), "| text chunks:", len(text_files), "| texts:", len(by_text), "| keys:", len(by_key))
print("DATA=" + ",".join(data_files)); print("TEXT=" + ",".join(text_files))
